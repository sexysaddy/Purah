"""Low-latency text cleanup and sentence segmentation for PURAH TTS.

Pure Python helpers kept separate so they can be tested without Qt/audio devices.
"""
from __future__ import annotations

import re

_ABBREVIATIONS = (
    "т.е.", "т.к.", "и т.д.", "и т.п.", "др.", "г.", "ул.", "пр.",
    "им.", "стр.", "рис.", "см.", "руб.", "тыс.", "млн.", "млрд.",
)


def clean_tts_text(text: str) -> str:
    """Strip common Markdown/URLs and normalize whitespace before speech synthesis."""
    text = re.sub(r"```.*?```", "блок кода", text, flags=re.S)
    text = re.sub(r"!\[[^\]]*\]\([^)]*\)", "изображение", text)
    text = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"https?://\S+", "ссылка", text)
    text = re.sub(r"[`*_#>]+", "", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text[:4000]


def _ends_sentence(buffer: str) -> bool:
    tail = buffer.rstrip()
    if not tail or not re.search(r"[.!?…][\"'»”’)]*$", tail):
        return False
    lower = tail.casefold()
    # Avoid treating common Russian abbreviations as a complete sentence.
    if lower.endswith(_ABBREVIATIONS):
        return False
    return True


def _preferred_cut(buffer: str, max_chars: int) -> int | None:
    """Pick a natural split in an overlong sentence, preferring punctuation."""
    prefix = buffer[:max_chars]
    punctuation = list(re.finditer(r"[,;:]\s+", prefix))
    if punctuation and punctuation[-1].end() >= int(max_chars * 0.55):
        return punctuation[-1].end()
    spaces = list(re.finditer(r"\s+", prefix))
    if spaces:
        return spaces[-1].end()
    return None


def extract_tts_segments(
    buffer: str,
    *,
    final: bool = False,
    max_chars: int = 220,
) -> tuple[list[str], str]:
    """Extract speakable sentence/phrase chunks while preserving unfinished text.

    When ``final`` is false, completed sentences are returned as soon as possible.
    A long sentence is split near punctuation/whitespace so it can be synthesized
    while later text is still being generated by the LLM.
    """
    max_chars = max(80, min(int(max_chars), 500))
    ready: list[str] = []
    remaining = buffer

    while remaining.strip():
        match = None
        for candidate in re.finditer(r"(?<=[.!?…])[\"'»”’)]*\s+", remaining):
            candidate_text = remaining[:candidate.end()].strip().casefold()
            # The period inside "т.е." / "т.к." must not end a spoken chunk.
            if candidate_text.endswith(_ABBREVIATIONS):
                continue
            match = candidate
            break
        cut: int | None = match.end() if match else None

        if cut is None and _ends_sentence(remaining):
            cut = len(remaining.rstrip())
        if cut is None and len(remaining) > max_chars:
            cut = _preferred_cut(remaining, max_chars)
        if cut is None and final:
            cut = len(remaining)
        if cut is None or cut <= 0:
            break

        raw = remaining[:cut].strip()
        clean = clean_tts_text(raw)
        if clean:
            ready.append(clean)
        remaining = remaining[cut:].lstrip()

    return ready, remaining
